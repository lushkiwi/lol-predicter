def history_variants(only: list[str] | None = None) -> None:
    """Validation comparison of the history-league choices. Each variant rebuilds the features
    (in a scratch directory) and fits the standard next-action recipe; nothing else changes.
    Writes reports/history_leagues.md. The test split is not touched. ``only``: run just these
    variants and reuse the saved results of the others."""
    import shutil

    from .features import build_engine
    from .ingest.oracles_elixir import load_history
    from .models.next_action import fit_with_refit

    games = pd.read_parquet(config.GAMES_PATH)
    tmp = config.DATA_PROCESSED / "features_history_tmp"
    era = np.datetime64(FEARLESS_ERA_START)
    res, rows = {}, []
    saved = pd.read_csv(RESULTS / "history_variants.csv").set_index("variant") if (RESULTS / "history_variants.csv").exists() else None
    in_scope_players = {p for col in ("blue_players", "red_players") for ps in games[col] for p in ps if p is not None}
    for name, (leagues, blocks) in HISTORY_VARIANTS.items():
        if only and name not in only and saved is not None and name in saved.index:
            res[name] = load_result(f"na_history_{name}_val")
            rows.append({"variant": name, **saved.loc[name].to_dict()})
            continue
        t = time.time()
        hist = load_history(leagues) if leagues else None
        data, _, _ = ds.build(games=games, engine=build_engine(history_blocks=blocks), out_dir=tmp, verbose=False, history=hist)
        idx = split_indices(data)
        dt = data.actions["datetime"].to_numpy()
        m = fit_with_refit(data, idx["fit"][dt[idx["fit"]] >= era], idx["tune"])
        res[name] = m.evaluate(data, idx["val"])
        save_result(f"na_history_{name}_val", res[name])
        covered = set() if hist is None else {p for col in ("blue_players", "red_players") for ps in hist[col] for p in ps if p is not None}
        rows.append({"variant": name, "history_leagues": ", ".join(leagues) or "-", "history_blocks": ", ".join(blocks) or "-",
                     "history_games": 0 if hist is None else len(hist),
                     "in_scope_players_with_history": len(in_scope_players & covered),
                     "stage1_rounds": m.stage1_best_iteration, **ev.next_action_metrics(res[name])})
        _log(f"history variant {name}: {rows[-1]} ({time.time() - t:.0f}s)")
        del data, m
    shutil.rmtree(tmp, ignore_errors=True)
    table = pd.DataFrame(rows)
    table.to_csv(RESULTS / "history_variants.csv", index=False)
    cmp_none = ev.compare_table(res, "none", NA_METRICS, kind="next_action")
    v = res["none"]
    out = ["# History-only leagues\n",
           "Generated by `python -m draft_analyzer.experiments history`. History-only games update the as-of statistics "
           "of the listed blocks through the same engine and the same end-time rule as every other game, but are never "
           "predicted, trained on or scored. Each variant rebuilds the features and refits the next-action model on the Fearless era (2025 on), the same "
           f"recipe. Validation split only ({sizes(v)}, {len(v)} actions); {len(in_scope_players)} players appear in the "
           "in-scope games.\n",
           md(table), "",
           "## Against no history (paired bootstrap by series, 95% CI)\n", md(cmp_none), ""]
    (config.REPORTS / "history_leagues.md").write_text("\n".join(out))
    print("\n".join(out))


def regime_seed_check(seeds: tuple[int, ...] = (1, 2)) -> None:
    """Does the regime ranking (all games with decay vs Fearless era only) hold under other seeds?
    Refits both with each seed (negative sampling and LightGBM) and compares on validation.
    Writes reports/regime_seeds.md. About 8 minutes per seed."""
    from .models.next_action import NextActionModel

    data = ds.load()
    idx = split_indices(data)
    dt = data.actions["datetime"].to_numpy()
    fit_era = idx["fit"][dt[idx["fit"]] >= np.datetime64(FEARLESS_ERA_START)]
    out = ["# Regime choice under other random seeds\n",
           "Generated by `python -m draft_analyzer.experiments seeds`. Validation split; `diff` is all games with "
           "365-day decay minus Fearless era only, paired bootstrap by series. Seed 0 is the main run in "
           "`M3_models.md`.\n"]
    for seed in seeds:
        res, rounds = {}, {}
        for name, fit_idx, kw in (("fearless_only", fit_era, {}), ("all_decay365", idx["fit"], {"half_life_days": 365.0})):
            s1 = NextActionModel(params={"seed": seed}, **kw).fit(data, fit_idx, idx["tune"], seed=seed)
            m = NextActionModel(params={"seed": seed}, **kw).fit(data, np.sort(np.concatenate([fit_idx, idx["tune"]])), None,
                                                             num_rounds=int(round(s1.best_iteration * 1.1)), seed=seed)
            m.temperature = dict(s1.temperature)
            res[name], rounds[name] = m.evaluate(data, idx["val"]), s1.best_iteration
            _log(f"seed {seed} {name}: {ev.next_action_metrics(res[name])}")
        out += [f"## Seed {seed} (early-stopping rounds: {rounds})\n",
                md(ev.compare_table(res, "fearless_only", NA_METRICS, kind="next_action")), ""]
    (config.REPORTS / "regime_seeds.md").write_text("\n".join(out))
    print("\n".join(out))


