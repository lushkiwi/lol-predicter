def m2() -> None:
    from .models.baselines import PresenceBaseline, WinBaseline

    data, win = ds.load(), ds.load_win()
    idx = split_indices(data)
    out = ["# M2 baselines\n", "Generated by `python -m draft_analyzer.experiments m2`. "
           "All statistics are as-of (computed only from games that finished before each game started).\n",
           "## Splits (by series start time)\n", md(split_table(data, win), ".0f"), ""]

    # ---- next action ----
    fit_idx = idx["train"][(data.actions["datetime"].to_numpy()[idx["train"]] >= np.datetime64(FEARLESS_ERA_START))]
    models = {"A_presence": PresenceBaseline(use_team=False).fit(data, fit_idx),
              "B_presence_team": PresenceBaseline(use_team=True).fit(data, fit_idx)}
    res = {}
    for name, m in models.items():
        for split in ("val", "test"):
            r = m.evaluate(data, idx[split])
            save_result(f"na_{name}_{split}", r)
            if split == "val":
                res[name] = r
    v = res["A_presence"]
    out += [f"## Next action baselines (validation: {sizes(v)}, {len(v)} actions)\n",
            "- **A**: as-of patch presence (pick + ban rate; current patch shrunk toward the 60-day long-run rate "
            "with 20 pseudo-games), unavailable champions excluded.",
            "- **B**: A plus the relevant team's recent pick frequency (acting team for a pick, opponent for a ban; "
            "60-day half-life).",
            "- Probabilities for log loss: `softmax(tau * log(stat + eps))` over available champions; "
            "`tau`, `eps` (and B's team weight `w`) fitted per action type on training games from 2025 on.\n",
            "Fitted parameters (tau, eps, w): " + json.dumps({k: m.params for k, m in models.items()}) + "\n"]
    for name, r in res.items():
        out += [f"### {name}\n", md(ev.next_action_report(r)), ""]
    out += ["### B vs A (paired bootstrap by series, 2000 resamples, 95% CI on the difference)\n",
            md(ev.compare_table(res, "A_presence", NA_METRICS, kind="next_action")), ""]
    for typ in ("pick", "ban"):
        sub = {k: r[r.action_type == typ] for k, r in res.items()}
        out += [f"{typ}s only:\n", md(ev.compare_table(sub, "A_presence", NA_METRICS, kind="next_action")), ""]
    uniform = float(np.mean(np.log(data.actions["n_cand"].to_numpy()[idx["val"]])))
    out += [f"Reference: a uniform guess over available champions has log loss {uniform:.4f} "
            f"(mean {data.actions['n_cand'].to_numpy()[idx['val']].mean():.0f} candidates per action).\n"]

    # ---- win ----
    w0 = win[win["k"] == 0]
    tr, va = w0[w0["split"] == "train"], w0[w0["split"] == "val"]
    wm = {"1_elo": WinBaseline("elo").fit(tr), "2_elo_side_fp": WinBaseline("elo_side_fp").fit(tr)}
    wres = {}
    for name, m in wm.items():
        wres[name] = m.evaluate(va)
        save_result(f"win_{name}_val", wres[name])
        save_result(f"win_{name}_test", m.evaluate(w0[w0["split"] == "test"]))
    const = wres["1_elo"].copy()
    const["p"] = float(tr["y"].mean())
    wres["0_constant_blue_rate"] = const
    out += [f"## Win baselines (validation: {sizes(va)})\n",
            "- **1**: logistic regression on the as-of Elo difference only (no intercept, so no side information).",
            "- **2**: Elo difference + intercept (blue side) + first-pick indicator.",
            "- Elo: K=28, ratings pulled 35% toward the league mean at season boundaries (grid-searched on the "
            "training period only). All leagues start at 1500, so cross-region gaps rest on few international games.\n",
            "Coefficients: " + json.dumps({k: m.describe() for k, m in wm.items()}) + "\n",
            md(pd.DataFrame([{"model": k, **ev.win_metrics(r)} for k, r in sorted(wres.items())])), "",
            "### vs baseline 1 (paired bootstrap by series)\n",
            md(ev.compare_table(wres, "1_elo", WIN_METRICS, kind="win")), ""]
    config.REPORTS.mkdir(exist_ok=True)
    table = ev.reliability_diagram({k: wres[k] for k in ("1_elo", "2_elo_side_fp")}, config.REPORTS / "m2_win_calibration.png",
                                   n_bins=10, title=f"Win baselines, validation ({sizes(va)})")
    out += ["### Calibration\n", "![calibration](m2_win_calibration.png)\n", md(table), ""]
    (config.REPORTS / "M2_baselines.md").write_text("\n".join(out))
    MODELS.mkdir(parents=True, exist_ok=True)
    with open(MODELS / "baselines.pkl", "wb") as f:
        pickle.dump({"next_action": models, "win": wm}, f)
    print("\n".join(out))


