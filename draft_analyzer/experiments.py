def m3_win() -> None:
    from .features import group_of
    from .models.baselines import WinBaseline
    from .models.win import BASE_FEATURES, WinGBM, WinModel, choose_C, draft_feature_columns, feature_columns

    win = ds.load_win()
    tr, va, te = (win[win["split"] == s] for s in ("train", "val", "test"))
    fit, tune = tr[tr["datetime"] < ds.TUNE_START], tr[tr["datetime"] >= ds.TUNE_START]
    feats = feature_columns(win)
    draft_feats = draft_feature_columns(win)
    summary: dict = {"features": feats, "draft_features": draft_feats}

    base1 = WinBaseline("elo").fit(tr[tr.k == 0])
    base2 = WinBaseline("elo_side_fp").fit(tr[tr.k == 0])

    def base_eval(m, frame):
        out = frame[["game_id", "series_id", "k", "y"]].reset_index(drop=True).copy()
        out["p"] = m.predict(frame)
        return out

    C, c_table = choose_C(fit, tune, feats)
    summary["C"], summary["C_table"] = C, c_table.to_dict("records")
    full = WinModel(feats, C=C).fit(tr)
    # same model without any draft feature: isolates what the draft adds beyond pre-game facts
    pre_feats = [f for f in feats if f not in draft_feats]
    C_pre, _ = choose_C(fit, tune, pre_feats)
    pregame = WinModel(pre_feats, C=C_pre).fit(tr)
    gbm_stage1 = WinGBM(feats).fit(fit, tune)
    gbm = WinGBM(feats).fit(tr, None, num_rounds=max(int(gbm_stage1.booster.best_iteration * 1.1), 10))
    summary["gbm_rounds"] = gbm_stage1.booster.best_iteration

    results = {}
    for split, frame in (("val", va), ("test", te)):
        results[split] = {
            "baseline1_elo": base_eval(base1, frame), "baseline2_elo_side_fp": base_eval(base2, frame),
            "lr_pregame_only": pregame.evaluate(frame), "lr_full": full.evaluate(frame), "gbm_full": gbm.evaluate(frame),
        }
        for name, r in results[split].items():
            save_result(f"win_{name}_{split}", r)

    # drop-one-group ablation of the draft features (logistic regression)
    groups = sorted({group_of(f) for f in draft_feats})
    for g in groups:
        keep = [f for f in feats if not (f in draft_feats and group_of(f) == g)]
        m = WinModel(keep, C=C).fit(tr)
        save_result(f"win_ablate_{g.replace('/', '_').replace(' ', '_')}_val", m.evaluate(va))
    summary["ablation_groups"] = groups
    full.coefficients().to_csv(RESULTS / "win_coefficients.csv", index=False)

    done = results["val"]
    k20 = {k: v[v.k == 20] for k, v in done.items()}
    ev.reliability_diagram({k: k20[k] for k in ("baseline2_elo_side_fp", "lr_full")}, config.REPORTS / "m3_win_calibration.png",
                           n_bins=10, title=f"Win model after the full draft, validation ({sizes(k20['lr_full'])})")
    MODELS.mkdir(parents=True, exist_ok=True)
    with open(MODELS / "win.pkl", "wb") as f:
        pickle.dump({"model": full, "baseline": base2, "baseline1": base1}, f)
    live_full = WinModel(feats, C=C).fit(win)
    with open(MODELS / "win_live.pkl", "wb") as f:
        pickle.dump({"model": live_full, "baseline": WinBaseline("elo_side_fp").fit(win[win.k == 0]),
                     "baseline1": WinBaseline("elo").fit(win[win.k == 0])}, f)
    (RESULTS / "win_summary.json").write_text(json.dumps(summary, indent=2, default=float))
    _log(f"win experiments done; C={C}; val k=20: " + json.dumps({k: ev.win_metrics(v) for k, v in k20.items()}, default=float))


def pack_models() -> None:
    """Bundle next-action + win models into the two files the CLI loads."""
    for suffix in ("", "_live"):
        with open(MODELS / f"next_action{suffix}.pkl", "rb") as f:
            na = pickle.load(f)
        with open(MODELS / f"win{suffix}.pkl", "rb") as f:
            wn = pickle.load(f)
        with open(MODELS / f"models{suffix}.pkl", "wb") as f:
            pickle.dump({"next_action": na, "win": wn}, f)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    {"build": build, "m2": m2, "m3na": m3_next_action, "m3win": m3_win, "pack": pack_models}.get(cmd, lambda: print(__doc__))()
