"""Assemble the milestone reports from saved tables/results.

    python -m draft_analyzer.report m1   # reports/M1_ingestion.md
    python -m draft_analyzer.report m3   # reports/M3_models.md (after experiments m3na + m3win)
"""
from __future__ import annotations

import json
import sys

import numpy as np
import pandas as pd

from . import config, evaluate as ev
from .experiments import NA_METRICS, RESULTS, WIN_METRICS, load_result, md, sizes


# --------------------------------------------------------------------------------------
def m1() -> None:
    g = pd.read_parquet(config.GAMES_PATH)
    a = pd.read_parquet(config.ACTIONS_PATH)
    fs = pd.read_csv(config.DATA_PROCESSED / "fearless_summary.csv")
    g["red_first_pick"] = g["first_pick_side"] == "Red"
    out = ["# M1 ingestion report\n", "Generated by `python -m draft_analyzer.report m1` from `data/processed/`.\n"]

    out += ["## Oracle's Elixir draft-order coverage\n",
            "Team rows carry `firstPick`, `ban1..5` and `pick1..5` (each team's own order). Coverage for the configured "
            "leagues, per OE season file:\n"]
    cov = (g.assign(picks_ok=g.apply(lambda r: None not in list(r.blue_picks) + list(r.red_picks), axis=1),
                    all_bans=g["n_missed_bans"] == 0, fp_ok=g["first_pick_side"].notna())
           .groupby(["oe_year", "league"])
           .agg(games=("game_id", "size"), series=("series_id", "nunique"), picks_complete=("picks_ok", "mean"),
                all_10_bans=("all_bans", "mean"), first_pick_known=("fp_ok", "mean"), red_first_pick=("red_first_pick", "mean"),
                first=("datetime", "min"), last=("datetime", "max")).reset_index())
    cov["first"], cov["last"] = cov["first"].astype(str).str[:10], cov["last"].astype(str).str[:10]
    out += [md(cov, ".3f"), ""]
    tot = g.groupby("oe_year").agg(games=("game_id", "size"), series=("series_id", "nunique"),
                                   red_first_pick=("red_first_pick", "mean")).reset_index()
    out += ["Totals per season file:\n", md(tot, ".3f"), "",
            f"**Total: {len(g)} games, {g.series_id.nunique()} series, {len(a)} draft actions "
            f"({int(a.champion.isna().sum())} of them missed bans).**\n"]

    out += ["## First Selection (2026): share of games where red had first pick\n"]
    g26 = g[g["datetime"] >= "2026-01-14"]
    main = g26[~g26["league"].isin(["LTA N", "LTA S"])]
    by = main.groupby("league").agg(games=("game_id", "size"), red_first_pick=("red_first_pick", "mean"),
                                    blue_win_rate=("winner_side", lambda s: (s == "Blue").mean())).reset_index()
    out += [md(by, ".3f"), "",
            f"Overall from 2026-01-14: red had first pick in **{main.red_first_pick.mean():.1%}** of {len(main)} games "
            f"(0% in every earlier game). Blue side won {(main.winner_side == 'Blue').mean():.1%}; the first-pick team won "
            f"{(main.first_pick_side == main.winner_side).mean():.1%}.\n"]

    out += ["## Fearless detection (empirical, per league / season / split / stage)\n",
            "`own_repeat_rate`: share of team-games (game 2+) where a team re-picked one of its own earlier champions; "
            "`opp_repeat_rate`: where it picked a champion the opponent used earlier. hard = neither ever happens, "
            "soft = only the second happens, none = both happen, na = no game 2+ (best-of-1 stage).\n",
            md(fs, ".3f"), "",
            "Games per detected mode: " + json.dumps(g["fearless"].value_counts().to_dict()) + "\n"]

    out += ["## Irregular drafts and missing data\n"]
    irr = g[g["irregular"]]
    kinds = irr["irregular_notes"].str.split(";").explode().str.replace(r":.*", "", regex=True).value_counts()
    out += [md(kinds.rename_axis("issue").reset_index(name="games"), ".0f"), "",
            f"- {len(irr)} games have a missed ban; they are kept, with a null `champion` for that action "
            "(always 20 rows per game in `draft_actions`).",
            "- 2 of those were recorded by OE as an impossible duplicate ban; Leaguepedia shows a missed ban, so the "
            "later duplicate is nulled.",
            f"- {int(g.series_incomplete.sum())} games belong to series whose game 1 is absent from OE "
            "(`series_incomplete`); their Fearless-burned lists are incomplete.",
            f"- {int(g.picks_in_role_order.sum())} games list both teams' picks exactly in role order "
            "(`picks_in_role_order`). 12 were checked against Leaguepedia: 10 are genuine, 2 (LEC 2026) are OE entries "
            "that lost the draft order. Left as is and flagged.",
            "- No game was dropped. Every game has exactly two team rows and ten player rows, one winner, and a "
            "first-pick flag on exactly one team.\n"]
    (config.REPORTS / "M1_ingestion.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    {"m1": m1}.get(cmd, lambda: print(__doc__))()
